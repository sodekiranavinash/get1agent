#!/usr/bin/env bash
# Write cloudflare/terraform.tfvars from the values the AWS stacks own.
#
# The Cloudflare env never reads the prod/web state directly (no
# terraform_remote_state), so a DNS-only plan can neither lock nor stale-depend
# on the AWS state. This script is the seam: it copies across the few values
# Cloudflare genuinely needs.
#
# Usage:
#   bash infra/aws/write-cloudflare-tfvars.sh
#
# No configuration is required: cloudflare_zone_id and cloudflare_zone_name have
# defaults in variables.tf, and it only needs to read the prod/web outputs. Set
# CLOUDFLARE_ZONE_ID / CLOUDFLARE_ZONE_NAME to override, or ENABLE_HSTS=true to
# turn HSTS on.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
TFVARS="$ROOT/infra/terraform/envs/cloudflare/terraform.tfvars"

# Neither id is required any more: cloudflare_zone_id and cloudflare_zone_name
# both have defaults in variables.tf. They are written only when supplied, which
# keeps CI configuration to a single credential and nothing else.
ZONE_ID="${CLOUDFLARE_ZONE_ID:-}"
ZONE_NAME="${CLOUDFLARE_ZONE_NAME:-}"

ENABLE_HSTS="${ENABLE_HSTS:-false}"

# Reading `terraform output` needs an initialised working dir *whose backend is
# S3*. Checking for `.terraform` is not enough: the Infra workflow runs
# `terraform init -backend=false` for validation first, which leaves the
# directory initialised but state-less. `terraform output` then returns nothing
# and the tfvars carry empty values — an empty CNAME does not just fail, it
# deletes the DNS record from the plan. Always re-init against the real backend;
# it is idempotent and reads only the backend metadata.
ensure_init() {
  local dir="$1"
  echo "Initialising $dir to read its outputs" >&2
  (cd "$dir" && terraform init -input=false -no-color -reconfigure >&2)
}

read_output() {
  local dir="$1" format="$2" name="$3"
  (cd "$dir" && terraform output "$format" "$name" 2>/dev/null) || true
}

PROD_DIR="$ROOT/infra/terraform/envs/prod"
WEB_DIR="$ROOT/infra/terraform/envs/web"
ensure_init "$PROD_DIR"
ensure_init "$WEB_DIR"

API_TARGET="$(read_output "$PROD_DIR" -raw api_gateway_cname_target)"
SITE_ENDPOINT="$(read_output "$WEB_DIR" -raw website_endpoint)"

ACM_JSON="$(read_output "$PROD_DIR" -json acm_validation_records)"
[[ -n "$ACM_JSON" && "$ACM_JSON" != "null" ]] || ACM_JSON='{}'

# Render the { domain => {name,type,value} } map as an HCL map literal.
ACM_HCL="$(printf '%s' "$ACM_JSON" | jq -r '
  to_entries
  | map("  \"\(.key)\" = { name = \"\(.value.name)\", type = \"\(.value.type)\", value = \"\(.value.value)\" }")
  | join("\n")
')"
[[ -n "$ACM_HCL" ]] || ACM_HCL="  # (no ACM validation records — custom domain disabled in prod)"

if [[ -z "$API_TARGET" ]]; then
  echo "ERROR: prod output api_gateway_cname_target is empty." >&2
  echo "       Refusing to write terraform.tfvars: an empty CNAME content makes" >&2
  echo "       Terraform destroy api.get1agent.com. Fix the prod stack (or its" >&2
  echo "       state/backend) before running Cloudflare." >&2
  exit 1
fi
if [[ -z "$SITE_ENDPOINT" ]]; then
  echo "ERROR: web output website_endpoint is empty — www origin cannot be resolved." >&2
  echo "       Refusing to write terraform.tfvars: an empty CNAME content would" >&2
  echo "       destroy www.get1agent.com. Apply the Web stack first." >&2
  exit 1
fi
if [[ -z "$ACM_JSON" || "$ACM_JSON" == "null" || "$ACM_JSON" == "{}" ]]; then
  echo "ERROR: prod output acm_validation_records is empty." >&2
  echo "       Refusing to write terraform.tfvars: an empty map plans a DESTROY of" >&2
  echo "       the ACM validation CNAME, and the certificate then fails to renew." >&2
  exit 1
fi

# Only emit the ids when they were provided; otherwise the variables.tf defaults win.
# `printf -v` rather than $(...) because command substitution strips the trailing
# newline, which would run the two lines together into invalid HCL.
ZONE_ID_BLOCK=""
[[ -n "$ZONE_ID" ]] && printf -v ZONE_ID_BLOCK 'cloudflare_zone_id   = "%s"\n' "$ZONE_ID"
ZONE_NAME_BLOCK=""
[[ -n "$ZONE_NAME" ]] && printf -v ZONE_NAME_BLOCK 'cloudflare_zone_name = "%s"\n' "$ZONE_NAME"

cat >"$TFVARS" <<EOF
# Generated by infra/aws/write-cloudflare-tfvars.sh — do not edit by hand.
# Credentials are never written here; they arrive as CLOUDFLARE_API_KEY +
# CLOUDFLARE_EMAIL (or CLOUDFLARE_API_TOKEN) in the environment.
${ZONE_ID_BLOCK}${ZONE_NAME_BLOCK}
# --- from envs/prod + envs/web ---
api_gateway_cname_target = "${API_TARGET}"
site_website_endpoint    = "${SITE_ENDPOINT}"

acm_validation_records = {
${ACM_HCL}
}

# --- HSTS guard (mirrors live state: disabled) ---
enable_hsts = ${ENABLE_HSTS}
EOF

echo "Wrote $TFVARS"
