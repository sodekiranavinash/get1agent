"""Generate AI Assistant's evaluation dataset from the corpus and the route catalogue.

The dataset is committed (``tools/ai-assistant-knowledge/eval/ai-assistant-eval.jsonl``) so a change
to it is reviewable, and regenerated by ``make ai-assistant-knowledge`` so it follows the
corpus. Each case names the page that *should* be cited, which turns "is AI Assistant
right?" into a machine-checkable question instead of a matter of opinion.

Six case kinds, chosen because they fail in different ways:

* ``answerable``  a real question with a known page — the core quality signal
* ``find``        "where do I…" — must return a valid, clickable route
* ``refuse``      off-topic and hostile — must decline, kindly
* ``boundary``    on-topic but easy to misclassify as off-topic (a unit conversion)
* ``unknown``     not documented — must say so instead of inventing an answer
* ``multiturn``   a follow-up that only resolves with the conversation history
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any

from sources import load_routes

#: Deterministic ids so a regenerated file diffs cleanly.
PREFIXES = {
    "answerable": "ans",
    "find": "find",
    "refuse": "ref",
    "boundary": "bnd",
    "unknown": "unk",
    "multiturn": "mt",
}


@dataclass
class EvalCase:
    id: str
    kind: str
    question: str
    #: The page a correct answer should cite (checked against the route table).
    expected_route: str = ""
    #: A phrase the answer should contain, when there is one canonical fact.
    expected_contains: list[str] = field(default_factory=list)
    #: For multiturn: the turns before the question.
    history: list[dict[str, str]] = field(default_factory=list)
    #: A note shown in the admin run view when a case fails.
    note: str = ""
    expect_refusal: bool = False

    def to_json(self) -> dict[str, Any]:
        payload: dict[str, Any] = {
            "id": self.id,
            "kind": self.kind,
            "question": self.question,
        }
        if self.history:
            payload["history"] = self.history
        if self.expected_route:
            payload["expectedRoute"] = self.expected_route
        if self.expected_contains:
            payload["expectedContains"] = self.expected_contains
        if self.expect_refusal:
            payload["expectRefusal"] = True
        if self.note:
            payload["note"] = self.note
        return payload


