def _route_exists(route: str, routes: set[str]) -> bool:
    path = route.split("#", 1)[0]
    if path in routes:
        return True
    for known in routes:
        if ":" in known:
            prefix = known.split(":", 1)[0].rstrip("/")
            if prefix and path.startswith(prefix + "/"):
                return True
    return False


def build_cases() -> list[EvalCase]:
    routes = {route.path for route in load_routes()}
    cases: list[EvalCase] = []

    for index, (question, route, note, contains) in enumerate(ANSWERABLE, start=1):
        cases.append(
            EvalCase(
                id=f"{PREFIXES['answerable']}-{index:03d}",
                kind="answerable",
                question=question,
                expected_route=route,
                expected_contains=list(contains),
                note=note,
            )
        )

    for index, (question, route) in enumerate(FIND, start=1):
        cases.append(
            EvalCase(
                id=f"{PREFIXES['find']}-{index:03d}",
                kind="find",
                question=question,
                expected_route=route,
                note="The answer must name an openable page.",
            )
        )

    for index, question in enumerate(REFUSE, start=1):
        cases.append(
            EvalCase(
                id=f"{PREFIXES['refuse']}-{index:03d}",
                kind="refuse",
                question=question,
                expect_refusal=True,
                note="Must decline warmly and offer example questions.",
            )
        )

    for index, (question, route) in enumerate(BOUNDARY, start=1):
        cases.append(
            EvalCase(
                id=f"{PREFIXES['boundary']}-{index:03d}",
                kind="boundary",
                question=question,
                expected_route=route,
                note="On-topic: must NOT be refused.",
            )
        )

    for index, question in enumerate(UNKNOWN, start=1):
        cases.append(
            EvalCase(
                id=f"{PREFIXES['unknown']}-{index:03d}",
                kind="unknown",
                question=question,
                note="Not documented: must say so and point at /support — never invent.",
            )
        )

    for index, (first, follow_up, route, note) in enumerate(MULTITURN, start=1):
        cases.append(
            EvalCase(
                id=f"{PREFIXES['multiturn']}-{index:03d}",
                kind="multiturn",
                question=follow_up,
                expected_route=route,
                history=[
                    {"role": "user", "content": first},
                    {"role": "assistant", "content": "(answered in the previous turn)"},
                ],
                note=note,
            )
        )

    # A dataset that names a page the app does not have is worse than no dataset:
    # the grader would mark correct answers wrong.
    for case in cases:
        if case.expected_route and not _route_exists(case.expected_route, routes):
            raise ValueError(
                f"eval case {case.id} expects {case.expected_route!r}, which is not a real route"
            )

    seen: set[str] = set()
    for case in cases:
        if case.question in seen:
            raise ValueError(f"duplicate eval question: {case.question!r}")
        seen.add(case.question)

    return cases


def render_jsonl(cases: list[EvalCase]) -> str:
    return "\n".join(json.dumps(case.to_json(), ensure_ascii=False) for case in cases) + "\n"


def summary(cases: list[EvalCase]) -> str:
    from collections import Counter

    counts = Counter(case.kind for case in cases)
    parts = ", ".join(f"{kind}={count}" for kind, count in sorted(counts.items()))
    return f"{len(cases)} eval cases ({parts})"
